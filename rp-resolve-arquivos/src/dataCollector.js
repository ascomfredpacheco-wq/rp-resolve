export function normalizeHandle(raw) {
  if (!raw || typeof raw !== 'string') return '';
  let cleaned = raw.trim();
  cleaned = cleaned.replace(/^https?:\/\/(www\.)?instagram\.com\//i, '');
  cleaned = cleaned.split('/')[0].split('?')[0];
  cleaned = cleaned.replace(/^@+/, '').trim().toLowerCase();
  return cleaned;
}

function hashString(str) {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h);
}

function inferNicheFromHandle(handle, nicheHint) {
  const byId = (id) => NICHE_CATALOG.find((n) => n.id === id) || NICHE_CATALOG[0];
  if (nicheHint) {
    const found = NICHE_CATALOG.find((n) => n.id === nicheHint);
    if (found) return found;
  }
  const lower = handle.toLowerCase();
  if (/adv|direito|jurid|lei|oab|juiz|promotor|defensor|doutor/.test(lower)) return byId('direito');
  if (/politic|deputad|veread|senad|prefeit|govern|mandato|cidada/.test(lower)) return byId('politica');
  if (/fit|gym|treino|muzy|cariani|nutri|saude/.test(lower)) return byId('fitness');
  if (/food|chef|receita|gastro|cozinha|doce/.test(lower)) return byId('gastronomia');
  if (/humor|comedia|meme|whindersson|tata/.test(lower)) return byId('humor');
  if (/music|som|cantor|alok|anitta/.test(lower)) return byId('musica');
  if (/viagem|turismo|destino|milhas|trip/.test(lower)) return byId('turismo');
  if (/news|noticia|jornal|g1|bbc/.test(lower)) return byId('noticias');
  if (/cine|pop|nerd|serie|game|omelete/.test(lower)) return byId('entretenimento');
  if (/eua|europa|portugal|exterior|gringa/.test(lower)) return byId('brasileiros_exterior');
  return byId('marketing');
}

